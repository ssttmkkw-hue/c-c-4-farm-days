export function t(lang, key, vars) {
  const row = STR[key];
  let s = row ? (row[lang] || row.zh) : key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.replaceAll('{' + k + '}', String(vars[k]));
    }
  }
  return s;
}

export function itemName(lang, id) {
  return t(lang, 'item_' + id);
}
